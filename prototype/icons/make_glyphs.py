#!/usr/bin/env python3
"""Rebuild ../glyphs.js, the logo shapes for the app icons, from the logo files in this folder.

Run it after adding or changing a logo file:  python3 make_glyphs.py
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / 'glyphs.js'

# Wordmarks are drawn wider than square logos.
WORDMARKS = {'prime', 'disney', 'apple', 'hbomax'}

# Extra shapes that the focus animations in style.css move, in each logo's own coordinates.
EXTRA = {
    # Twitch: lids that close over the mascot's eyes.
    'twitch': '<g class="sig-blink"><rect x="11.571" y="4.714" width="1.715" height="5.143"/>'
              '<rect x="16.286" y="4.714" width="1.714" height="5.143"/></g>',
    # Disney+: a sparkle that glides along the arc (circle centre 544,440, radius 435).
    'disney': '<g class="sig-sparkle"><path d="M979 385l14 41 41 14-41 14-14 41-14-41-41-14 41-14z"/></g>',
}


def glyph(name):
    text = (HERE / f'{name}.svg').read_text()
    # Each file is a 720x404 tile: a background rectangle and the logo in a nested <svg>.
    inner = list(re.finditer(r'<svg\b[^>]*>', text))[1]
    body = text[inner.end():text.rindex('</svg>', 0, text.rindex('</svg>'))]
    if name == 'disney':
        shapes = ''.join(f'<path d="{d}"/>' for d in re.findall(r'<path class="st0" d="([^"]+)"', body))
    else:
        shapes = ''.join(re.sub(r'\s*/>$', '/>', m.group(0)) for m in re.finditer(r'<(?:path|circle)\b[^>]*/>', body))
    if name == 'browser':
        shapes = shapes.replace('<path d="M12 2a14.5', '<path class="sig-spin" d="M12 2a14.5')
    g = {'box': re.search(r'viewBox="([^"]+)"', inner.group(0)).group(1), 'shape': shapes + EXTRA.get(name, '')}
    if 'stroke=' in inner.group(0):
        g['stroke'] = True
    if name in WORDMARKS:
        g['word'] = True
    return g


names = sorted(p.stem for p in HERE.glob('*.svg'))
lines = ['/* Logo shapes for the app icons, generated by icons/make_glyphs.py from the logo files in icons/',
         '   (sources and licences in icons/SOURCES.txt). Brand names and logos belong to their owners. */',
         'window.HOME_GLYPHS = {']
lines += [f'  {n}: {json.dumps(glyph(n))}' + (',' if i < len(names) - 1 else '') for i, n in enumerate(names)]
OUT.write_text('\n'.join(lines + ['};']) + '\n')
print(f'wrote {OUT.name}: {", ".join(names)}')
