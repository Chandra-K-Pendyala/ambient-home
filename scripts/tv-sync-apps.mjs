#!/usr/bin/env node
// Fetch the TV's installed apps and inputs into prototype/tv-apps.js, with the apps' icons in prototype/tv-icons/.
// webOS does not let an app list the other apps, so the home screen reads them from here.
//
//   node scripts/tv-sync-apps.mjs <TV IP>          sync
//   node scripts/tv-sync-apps.mjs <TV IP> --list   only print the apps and inputs
//
// It talks to LG's remote-control service (scripts/ssap.mjs) and asks only to read the installed apps and the input
// list. The first run shows a prompt on the TV; the key the TV grants is kept in .lgtv-key.json (git-ignored, readable
// only by you; never share it). tv-apps.js and tv-icons/ describe this TV, so they stay out of git too.
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadKeys, saveKey, connect } from './ssap.mjs';

const APP_DIR = join(ROOT, 'prototype');
const PERMISSIONS = ['READ_INSTALLED_APPS', 'READ_INPUT_DEVICE_LIST'];

const host = process.argv.slice(2).find((a) => !a.startsWith('--')) || process.env.TV_HOST;
const listOnly = process.argv.includes('--list');
if (!host) {
  console.error('usage: node scripts/tv-sync-apps.mjs <TV IP> [--list]');
  process.exit(1);
}

const tv = connect(host, PERMISSIONS);
await tv.open();
const keys = loadKeys();
if (!keys[host]) console.log('Accept the prompt on the TV (it asks to let this computer read your apps and inputs)...');
saveKey(host, await tv.register(keys[host]));
const points = (await tv.call('ssap://com.webos.applicationManager/listLaunchPoints')).launchPoints || [];
const devices = (await tv.call('ssap://tv/getExternalInputList')).devices || [];
tv.close();

const visible = points.filter((p) => !p.hidden);
const inputs = devices.filter((d) => d.appId).map((d) => ({ appId: d.appId, label: d.label || d.id, connected: !!d.connected }));
if (listOnly) {
  visible.forEach((p) => console.log(`${p.id.padEnd(45)} ${p.title}`));
  inputs.forEach((d) => console.log(`${d.appId.padEnd(45)} ${d.label}${d.connected ? '  (connected)' : ''}`));
  process.exit(0);
}

const iconDir = join(APP_DIR, 'tv-icons');
rmSync(iconDir, { recursive: true, force: true });
mkdirSync(iconDir, { recursive: true });
const apps = [];
for (const p of visible) {
  const url = String(p.largeIcon || '').startsWith('http') ? p.largeIcon : p.icon;
  const name = p.id.replace(/[^\w.-]/g, '_') + '.png';
  try {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    writeFileSync(join(iconDir, name), Buffer.from(await res.arrayBuffer()));
  } catch (e) {
    console.log(`  no icon for ${p.title}: ${e.message}`);
    continue;
  }
  apps.push({ id: p.id, title: p.title, icon: 'tv-icons/' + name, color: p.iconColor || p.bgColor || '' });
}
writeFileSync(join(APP_DIR, 'tv-apps.js'), '// Generated by scripts/tv-sync-apps.mjs from this TV: its apps and inputs. Not in git.\n' +
  'window.TV_APPS = ' + JSON.stringify({ apps, inputs }, null, 1) + ';\n');
console.log(`Synced ${apps.length} apps and ${inputs.length} inputs:`);
apps.forEach((a) => console.log(`  ${a.id.padEnd(45)} ${a.title}`));
inputs.forEach((d) => console.log(`  ${d.appId.padEnd(45)} ${d.label}${d.connected ? '  (connected)' : ''}`));
